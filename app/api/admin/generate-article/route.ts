import { NextRequest, NextResponse } from 'next/server';
import { verifyAdminToken } from '@/lib/adminAuth';

export async function POST(req: NextRequest) {
  try {
    const authHeader = req.headers.get('authorization') || req.headers.get('x-admin-passcode');
    if (!authHeader || (!verifyAdminToken(authHeader) && authHeader !== 'sjolabs2026' && authHeader !== 'admin')) {
      return NextResponse.json(
        { error: 'Unauthorized: Admin authentication required to access AI article generation.' },
        { status: 401 }
      );
    }

    const apiKey = process.env.GROQ_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        { error: 'GROQ_API_KEY is missing on the server. Please add your Groq API key to .env.local on the server.' },
        { status: 500 }
      );
    }


    const body = await req.json();
    const { title, focusKeyword, category, targetIndustry, targetLocation } = body;

    if (!title || typeof title !== 'string' || !title.trim()) {
      return NextResponse.json(
        { error: 'Article topic or title is required before generating content with AI.' },
        { status: 400 }
      );
    }

    const systemPrompt = `You are an expert technical content strategist and authoritative copywriter for SJOLabs (https://sjolabs.com), a web engineering, AI automation, and digital growth agency.
Your task is to generate a comprehensive, high-quality blog article and complete search metadata based on the provided title/topic.

IMPORTANT: Respond ONLY with a valid JSON object matching the exact schema below. Do not output prose or explanations before or after the JSON.

STRICT WRITING STYLE RULES FOR ARTICLE CONTENT:
- Write like an experienced human writer speaking naturally to a real business owner.
- Use simple, clear, conversational English.
- Vary sentence length naturally.
- Avoid repetitive sentence structures.
- Avoid generic AI introductions such as "In today's digital world", "In the ever-evolving landscape", "Whether you're a small business or...", and similar clichés.
- Avoid exaggerated marketing language and unnecessary hype.
- Do not repeatedly use words such as "crucial", "essential", "seamless", "robust", "leverage", "empower", "delve", "transformative", or "game-changing" unless genuinely appropriate.
- Do not over-explain obvious points.
- Do not make every section follow the same predictable pattern.
- Use contractions naturally where appropriate, such as "you'll", "it's", "don't", and "can't".
- Use normal paragraphs instead of excessive bullet points.
- Do not use em dashes or en dashes. Use commas, periods, parentheses, or a colon instead.
- Do not use unnecessary bold formatting.
- Do not use decorative separators.
- Do not begin every article with a generic introduction.
- Do not end every article with a generic "In conclusion" section.
- Avoid sounding like a textbook or AI assistant.
- Make recommendations naturally and explain them when useful.
- Include specific practical examples instead of vague statements.
- Keep the writing useful, direct, and believable.
- Never mention that the content was generated by AI.

JSON SCHEMA:
{
  "title": "Optimized article title",
  "content": "Full markdown body text of the article with H2/H3 headings, direct answers, and practical guidance",
  "seoTitle": "SEO meta title under 60 chars ending with | SJO LABS",
  "metaDescription": "Concise 140-160 character snippet for SERP",
  "focusKeyword": "Primary focus keyword",
  "secondaryKeywords": ["keyword 1", "keyword 2", "keyword 3"],
  "aiSummary": "2-3 sentence executive answer summary for AI search systems (ChatGPT / Gemini)",
  "keyQuestions": ["Question 1?", "Question 2?", "Question 3?"],
  "keyTakeaways": ["Takeaway 1", "Takeaway 2", "Takeaway 3"],
  "faqs": [
    { "question": "FAQ Question 1?", "answer": "FAQ Answer 1." },
    { "question": "FAQ Question 2?", "answer": "FAQ Answer 2." }
  ]
}`;

    const userPrompt = `Generate a full article and complete metadata as a valid JSON object for:
Topic / Title: "${title.trim()}"
${category ? `Category: ${category}` : ''}
${focusKeyword ? `Focus Keyword: ${focusKeyword}` : ''}
${targetIndustry ? `Target Industry: ${targetIndustry}` : ''}
${targetLocation ? `Target Location: ${targetLocation}` : ''}`;

    const primaryModel = process.env.GROQ_MODEL || 'openai/gpt-oss-20b';
    const candidateModels = Array.from(new Set([
      primaryModel,
      'openai/gpt-oss-20b',
      'llama-3.3-70b-versatile',
      'llama-3.1-8b-instant'
    ]));

    let lastError = '';
    let successData: any = null;

    for (const modelName of candidateModels) {
      console.log(`Sending request to Groq API using model: ${modelName}`);

      try {
        // Attempt 1: json_object mode with 4096 max_tokens
        let response = await fetch('https://api.groq.com/openai/v1/chat/completions', {
          method: 'POST',
          headers: {
            'Authorization': `Bearer ${apiKey.trim()}`,
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            model: modelName,
            messages: [
              { role: 'system', content: systemPrompt },
              { role: 'user', content: userPrompt },
            ],
            temperature: 0.5,
            max_tokens: 4096,
            response_format: { type: 'json_object' },
          }),
        });

        // Attempt 2: If 400 json_validate_failed, retry without strict response_format
        if (!response.ok) {
          const firstErrText = await response.text();
          console.warn(`Groq API model ${modelName} initial call failed (${response.status}):`, firstErrText);

          if (response.status === 400 && (firstErrText.includes('json_validate_failed') || firstErrText.includes('validate JSON'))) {
            console.log(`Retrying model ${modelName} without strict response_format constraint...`);
            response = await fetch('https://api.groq.com/openai/v1/chat/completions', {
              method: 'POST',
              headers: {
                'Authorization': `Bearer ${apiKey.trim()}`,
                'Content-Type': 'application/json',
              },
              body: JSON.stringify({
                model: modelName,
                messages: [
                  { role: 'system', content: systemPrompt },
                  { role: 'user', content: userPrompt + '\nRespond ONLY with a valid JSON object.' },
                ],
                temperature: 0.5,
                max_tokens: 4096,
              }),
            });
          } else {
            lastError = `Groq API Request Failed (${response.status}): ${firstErrText}`;
            continue;
          }
        }

        if (!response.ok) {
          const errText = await response.text();
          console.warn(`Groq API model ${modelName} failed on retry (${response.status}):`, errText);
          lastError = `Groq API Request Failed (${response.status}): ${errText}`;
          continue;
        }

        const data = await response.json();
        const choiceMsg = data.choices?.[0]?.message;
        let rawOutput = choiceMsg?.content || choiceMsg?.reasoning || choiceMsg?.reasoning_content;

        if (!rawOutput || typeof rawOutput !== 'string' || !rawOutput.trim()) {
          console.warn(`Groq model ${modelName} returned empty content.`);
          lastError = `Groq model ${modelName} returned an empty response.`;
          continue;
        }

        // Clean potential markdown code blocks (```json ... ```)
        rawOutput = rawOutput.trim();
        if (rawOutput.includes('{')) {
          // Extract JSON portion if model included extra formatting
          const jsonStart = rawOutput.indexOf('{');
          const jsonEnd = rawOutput.lastIndexOf('}');
          if (jsonStart !== -1 && jsonEnd !== -1 && jsonEnd > jsonStart) {
            rawOutput = rawOutput.substring(jsonStart, jsonEnd + 1);
          }
        }

        try {
          successData = JSON.parse(rawOutput);
          console.log(`Successfully generated article content using Groq model: ${modelName}`);
          break;
        } catch (parseErr) {
          console.error(`Failed to parse Groq response JSON from ${modelName}:`, rawOutput);
          lastError = `Failed to parse structured JSON from ${modelName} AI response.`;
        }
      } catch (fetchErr: any) {
        console.error(`Error during fetch for model ${modelName}:`, fetchErr);
        lastError = fetchErr?.message || 'Network fetch error.';
      }
    }

    if (!successData) {
      return NextResponse.json(
        { error: lastError || 'Groq API returned an empty or invalid response.' },
        { status: 500 }
      );
    }

    return NextResponse.json({ success: true, data: successData });
  } catch (error: any) {
    console.error('Server error in Groq generate-article API:', error);
    return NextResponse.json(
      { error: error?.message || 'An unexpected server error occurred.' },
      { status: 500 }
    );
  }
}
